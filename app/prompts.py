def system_prompt(lang: str, mode: str = "ask") -> str:
    mode_text = MODE_PROMPTS.get(mode, "")
    for key, value in HEADINGS.get(lang, HEADINGS["ru"]).items():
        mode_text = mode_text.replace("{" + key + "}", value)
    return SYSTEM_PROMPT.replace("{lang_name}", LANG_NAMES.get(lang, "русский")) + mode_text


def format_documents(hits) -> str:
    """Собирает найденные фрагменты в XML-блок <documents> для LLM."""
    parts = []
    for n, h in enumerate(hits, 1):
        c = h.chunk
        attrs = [f'index="{n}"', f'type="{TYPE_LABELS.get(c["type"], c["type"])}"',
                 f'title="{c["title"]}"']
        if c.get("date"):
            attrs.append(f'date="{c["date"]}"')
        if c.get("article"):
            attrs.append(f'article="{c["article"]}"')
        if c.get("section"):
            attrs.append(f'section="{c["section"]}"')
        parts.append(f"<document {' '.join(attrs)}>\n{c['text']}\n</document>")
    return "<documents>\n" + "\n".join(parts) + "\n</documents>"


